/*
 * Client-side iPXE boot-script renderer.
 *
 * Mirrors `BootConfig.render` (resources/app/services/boot_config.py) so the
 * preview updates instantly while typing. The server is still authoritative:
 * on save the config and the on-disk boot.ipxe are regenerated from the same
 * Python logic, which is what the nodes actually pull.
 *
 * Exposes `window.bootRenderScript(form, controllerDefault)`.
 */
(function (root) {
    "use strict";

    function cleanText(value) {
        return (value == null ? "" : String(value))
            .replace(/[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]/g, "")
            .trim();
    }

    function render(form, controllerDefault) {
        function val(name) {
            var el = form.elements[name];
            return el ? el.value : "";
        }
        function on(name) {
            var el = form.elements[name];
            if (!el) return false;
            if (el.type === "checkbox") return !!el.checked;
            return cleanText(el.value) !== "";
        }

        var iface = cleanText(val("interface")) || "net0";
        var controller = cleanText(val("controller_url")) || controllerDefault || "";
        var filesBase = cleanText(val("files_url")).replace(/\/+$/, "");
        var lines = ["#!ipxe"];

        if (on("include_comments")) {
            lines.push("# generated by iPXE-PveController");
            lines.push("# ${controller} below is an iPXE variable; it is set from the Controller URL.");
        }
        if (on("set_controller_var")) lines.push("set controller " + controller);
        if (filesBase) lines.push("set files " + filesBase);

        if (on("use_dhcp")) {
            lines.push("dhcp");
        } else {
            if (cleanText(val("client_ip"))) lines.push("set " + iface + "/ip " + cleanText(val("client_ip")));
            if (cleanText(val("client_netmask"))) lines.push("set " + iface + "/netmask " + cleanText(val("client_netmask")));
            if (cleanText(val("client_gateway"))) lines.push("set " + iface + "/gateway " + cleanText(val("client_gateway")));
            if (cleanText(val("client_dns"))) lines.push("set " + iface + "/dns " + cleanText(val("client_dns")));
            lines.push("ifopen " + iface);
        }

        var captureMac = on("capture_mac");
        if (captureMac) lines.push("set node-mac ${" + iface + "/mac}");
        if (on("echo_mac")) {
            lines.push("echo Booting node " + (captureMac ? "${node-mac}" : "${" + iface + "/mac}"));
        }
        if (on("echo_report")) lines.push("echo Reporting to ${controller}/api/boot/report");
        if (cleanText(val("next_server"))) lines.push("set next-server " + cleanText(val("next_server")));

        String(val("variables") || "").split(/\r?\n/).forEach(function (line) {
            line = line.trim();
            if (!line || line.indexOf("=") === -1) return;
            var idx = line.indexOf("=");
            var name = line.slice(0, idx).trim();
            if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) return;
            lines.push("set " + name + " " + cleanText(line.slice(idx + 1)));
        });

        String(val("custom_lines") || "").split(/\r?\n/).forEach(function (line) {
            var cleaned = line.replace(/[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]/g, "").replace(/\s+$/, "");
            if (cleaned.trim()) lines.push(cleaned);
        });

        var sleepSeconds = parseInt(val("sleep_seconds"), 10) || 0;
        if (sleepSeconds > 0) lines.push("sleep " + sleepSeconds);
        var promptTimeout = parseInt(val("prompt_timeout"), 10) || 0;
        if (promptTimeout > 0) lines.push("prompt --timeout " + promptTimeout + " Press any key to abort autoboot");

        var action = cleanText(val("action")) || "kernel";
        if (action === "kernel") {
            var fileUrl = function (nameKey, urlKey, defaultName) {
                var override = cleanText(val(urlKey));
                var name = cleanText(val(nameKey)).replace(/^\/+/, "");
                if (!name && filesBase) name = defaultName;
                if (!override && name.indexOf("://") !== -1) { override = name; name = ""; }
                if (override) {
                    if (filesBase && override.indexOf(filesBase + "/") === 0) {
                        return "${files}/" + override.slice(filesBase.length + 1);
                    }
                    return override;
                }
                if (!name) return "";
                if (filesBase) return "${files}/" + name;
                return controller + "/bootfiles/" + name;
            };

            var kernel = fileUrl("kernel_file", "kernel_url", "vmlinuz");
            var initrd = fileUrl("initrd_file", "initrd_url", "initrd.img");
            var fetchUrl = fileUrl("squashfs_file", "squashfs_url", "root.squashfs");
            if (kernel) {
                var args = [];
                var cmdline = cleanText(val("kernel_cmdline")) || "boot=live ${fetch} ip=dhcp";
                if (cmdline.indexOf("${fetch}") !== -1) {
                    cmdline = cmdline.split("${fetch}").join(fetchUrl ? "fetch=" + fetchUrl : "");
                    cmdline = cmdline.split(/\s+/).join(" ").trim();
                } else if (fetchUrl) {
                    cmdline = (cmdline + " fetch=" + fetchUrl).trim();
                }
                if (cmdline) args.push(cmdline);
                if (on("pass_cmdline_vars")) {
                    args.push("pve_ctrl=${controller}");
                    if (captureMac) args.push("pve_mac=${node-mac}");
                }
                var extra = cleanText(val("boot_args"));
                if (extra) args.push(extra);
                var suffix = args.length ? " " + args.join(" ") : "";
                lines.push("kernel " + kernel + " initrd=initrd.img" + suffix);
                if (initrd) lines.push("initrd " + initrd);
                lines.push("boot");
            } else {
                lines.push("echo No kernel file/URL configured (set it in the Boot tab).");
                lines.push("sleep 5");
                lines.push("exit");
            }
        } else if (action === "shell") {
            lines.push("shell");
        } else if (action === "exit") {
            lines.push("exit");
        } else {
            var chainUrl = cleanText(val("chain_url"));
            if (chainUrl) {
                lines.push("chain " + chainUrl);
            } else {
                lines.push("echo No chain URL configured (set it in the Boot tab).");
                lines.push("sleep 5");
                lines.push("exit");
            }
        }

        return lines.join("\n") + "\n";
    }

    root.bootRenderScript = render;
})(typeof window !== "undefined" ? window : this);
