"""iPXE boot-script configuration.

All editable options live in the `settings` table under ``pxe.boot_config``
(JSON). `render()` turns them into a valid iPXE script that
`BootScriptController` serves at ``/boot.ipxe``.

Only admins can change these; the values are still sanitised (control
characters removed) so a stray byte cannot corrupt the generated script.
"""

from __future__ import annotations

import json
import re
from typing import Any

from config import get_config
from resources.app.models.setting import Setting

KEY = "pxe.boot_config"

_CONTROL_RE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")
_VAR_NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

DEFAULTS: dict[str, Any] = {
    # General
    "controller_url": "",  # empty -> use APP_URL; exposed as ${controller}
    "files_url": "",  # base URL of the file server; exposed as ${files}
    "next_server": "",  # DHCP option 66 / iPXE next-server
    "boot_file": "boot.ipxe",  # DHCP option 67 (informational)
    # Client network (static IP; ignored when `use_dhcp` is on)
    "use_dhcp": True,
    "client_ip": "",
    "client_netmask": "255.255.255.0",
    "client_gateway": "",
    "client_dns": "",
    # Script content toggles
    # NOTE: by default the script references NO network interface, so the very
    # same boot.ipxe works on every server regardless of which NIC it boots
    # from. The MAC is detected inside the image by the agent script.
    "capture_mac": False,  # optional: set node-mac=${iface}/mac
    "echo_mac": False,  # optional: echo the MAC
    "echo_report": False,  # optional: echo the reporting URL
    "set_controller_var": True,  # set controller=<url>
    "include_comments": True,
    # Boot action
    "action": "kernel",  # kernel | chain | exit | shell
    "pass_cmdline_vars": True,  # add pve_ctrl=... to the cmdline
    "chain_url": "",
    # Files are referenced as <files_url>/<name> when files_url is set, else as
    # <controller>/bootfiles/<name> (the uploaded files). With a file server set,
    # empty names fall back to vmlinuz / initrd.img / root.squashfs.
    "kernel_file": "",
    "initrd_file": "",
    "squashfs_file": "",
    "kernel_url": "",  # manual override (wins over kernel_file)
    "initrd_url": "",  # manual override (wins over initrd_file)
    "squashfs_url": "",  # manual override (wins over squashfs_file)
    "kernel_cmdline": "boot=live ${fetch} ip=dhcp",
    "boot_args": "",
    # Timing
    "sleep_seconds": 0,
    "prompt_timeout": 0,
    # Advanced (raw)
    "interface": "net0",  # NIC used to read the MAC (net0, net1, ...)
    "variables": "",  # one NAME=value per line -> `set NAME value`
    "custom_lines": "",  # raw extra lines
}

TOGGLES = (
    "use_dhcp",
    "capture_mac",
    "echo_mac",
    "echo_report",
    "set_controller_var",
    "include_comments",
    "pass_cmdline_vars",
)

# Conventional Proxmox netboot file names, used when a file server is set but no
# explicit name was given.
FILE_DEFAULTS = {
    "kernel_file": "vmlinuz",
    "initrd_file": "initrd.img",
    "squashfs_file": "root.squashfs",
}

MAC_VAR = "node-mac"


def _clean(value: Any) -> str:
    """Remove control characters (except tab/newline) and trim."""
    return _CONTROL_RE.sub("", str(value if value is not None else "")).strip()


class BootConfig:
    # -- persistence --------------------------------------------------------
    @classmethod
    def load(cls) -> dict[str, Any]:
        config = dict(DEFAULTS)
        raw = Setting.get(KEY)
        if raw:
            try:
                stored = json.loads(raw)
                if isinstance(stored, dict):
                    config.update({k: v for k, v in stored.items() if k in DEFAULTS})
            except json.JSONDecodeError:
                pass
        else:
            # First run: seed from the legacy per-key settings.
            config["next_server"] = Setting.get("pxe.next_server") or ""
            config["boot_file"] = Setting.get("pxe.boot_file") or config["boot_file"]
        return config

    @classmethod
    def save(cls, config: dict[str, Any]) -> None:
        merged = {**DEFAULTS, **{k: v for k, v in config.items() if k in DEFAULTS}}
        Setting.put(KEY, json.dumps(merged))
        # Keep the legacy keys in sync so other views/DHCP notes stay accurate.
        Setting.put("pxe.next_server", str(merged.get("next_server") or ""))
        Setting.put("pxe.boot_file", str(merged.get("boot_file") or ""))

    # -- rendering ----------------------------------------------------------
    @classmethod
    def render(cls, config: dict[str, Any] | None = None) -> str:
        cfg = {**DEFAULTS, **(config or {})}
        iface = _clean(cfg.get("interface")) or "net0"
        controller = _clean(cfg.get("controller_url")) or get_config().url
        files_base = _clean(cfg.get("files_url")).rstrip("/")
        lines: list[str] = ["#!ipxe"]

        if cfg.get("include_comments"):
            lines.append("# generated by iPXE-PveController")
            lines.append("# ${controller} below is an iPXE variable; it is set from the Controller URL.")

        if cfg.get("set_controller_var"):
            lines.append(f"set controller {controller}")

        if files_base:
            lines.append(f"set files {files_base}")

        if cfg.get("use_dhcp", True):
            lines.append("dhcp")
        else:
            if cfg.get("client_ip"):
                lines.append(f"set {iface}/ip {_clean(cfg['client_ip'])}")
            if cfg.get("client_netmask"):
                lines.append(f"set {iface}/netmask {_clean(cfg['client_netmask'])}")
            if cfg.get("client_gateway"):
                lines.append(f"set {iface}/gateway {_clean(cfg['client_gateway'])}")
            if cfg.get("client_dns"):
                lines.append(f"set {iface}/dns {_clean(cfg['client_dns'])}")
            lines.append(f"ifopen {iface}")

        capture_mac = bool(cfg.get("capture_mac"))
        if capture_mac:
            lines.append(f"set {MAC_VAR} ${{{iface}/mac}}")
        if cfg.get("echo_mac"):
            mac_ref = f"${{{MAC_VAR}}}" if capture_mac else f"${{{iface}/mac}}"
            lines.append(f"echo Booting node {mac_ref}")
        if cfg.get("echo_report"):
            lines.append("echo Reporting to ${controller}/api/boot/report")
        if cfg.get("next_server"):
            lines.append(f"set next-server {_clean(cfg['next_server'])}")

        for name, value in cls._parse_variables(cfg.get("variables")):
            lines.append(f"set {name} {value}")

        for raw_line in str(cfg.get("custom_lines") or "").splitlines():
            line = _CONTROL_RE.sub("", raw_line).rstrip()
            if line.strip():
                lines.append(line)

        sleep_seconds = cls._as_int(cfg.get("sleep_seconds"), 0)
        if sleep_seconds > 0:
            lines.append(f"sleep {sleep_seconds}")
        prompt_timeout = cls._as_int(cfg.get("prompt_timeout"), 0)
        if prompt_timeout > 0:
            lines.append(f"prompt --timeout {prompt_timeout} Press any key to abort autoboot")

        action = str(cfg.get("action") or "kernel")
        if action == "kernel":
            def file_url(name_key: str, url_key: str, default_name: str) -> str:
                override = _clean(cfg.get(url_key))
                name = _clean(cfg.get(name_key)).lstrip("/")
                if not name and files_base:
                    name = default_name
                # A full URL in the name field counts as an override.
                if not override and "://" in name:
                    override, name = name, ""
                if override:
                    # Normalise URLs that live on the file server to ${files}/<name>.
                    if files_base and override.startswith(files_base + "/"):
                        return f"${{files}}/{override[len(files_base) + 1:]}"
                    return override
                if not name:
                    return ""
                if files_base:
                    return f"${{files}}/{name}"
                return f"{controller}/bootfiles/{name}"

            kernel = file_url("kernel_file", "kernel_url", FILE_DEFAULTS["kernel_file"])
            initrd = file_url("initrd_file", "initrd_url", FILE_DEFAULTS["initrd_file"])
            fetch = file_url("squashfs_file", "squashfs_url", FILE_DEFAULTS["squashfs_file"])
            if kernel:
                args: list[str] = []
                # An empty cmdline falls back to the standard PVE boot line.
                cmdline = _clean(cfg.get("kernel_cmdline")) or DEFAULTS["kernel_cmdline"]
                if "${fetch}" in cmdline:
                    cmdline = cmdline.replace("${fetch}", f"fetch={fetch}" if fetch else "")
                    cmdline = " ".join(cmdline.split())
                elif fetch:
                    cmdline = (cmdline + " " + f"fetch={fetch}").strip()
                if cmdline:
                    args.append(cmdline)
                if cfg.get("pass_cmdline_vars"):
                    args.append("pve_ctrl=${controller}")
                    if capture_mac:
                        args.append(f"pve_mac=${{{MAC_VAR}}}")
                extra = _clean(cfg.get("boot_args"))
                if extra:
                    args.append(extra)
                suffix = (" " + " ".join(args)) if args else ""
                lines.append(f"kernel {kernel} initrd=initrd.img{suffix}")
                if initrd:
                    lines.append(f"initrd {initrd}")
                lines.append("boot")
            else:
                lines.append("echo No kernel file/URL configured (set it in the Boot tab).")
                lines.append("sleep 5")
                lines.append("exit")
        elif action == "shell":
            lines.append("shell")
        elif action == "exit":
            lines.append("exit")
        else:  # chain
            chain_url = _clean(cfg.get("chain_url"))
            if chain_url:
                lines.append(f"chain {chain_url}")
            else:
                lines.append("echo No chain URL configured (set it in the Boot tab).")
                lines.append("sleep 5")
                lines.append("exit")

        return "\n".join(lines) + "\n"

    # -- helpers ------------------------------------------------------------
    @staticmethod
    def _parse_variables(raw: Any) -> list[tuple[str, str]]:
        variables: list[tuple[str, str]] = []
        for line in str(raw or "").splitlines():
            line = line.strip()
            if not line or "=" not in line:
                continue
            name, _, value = line.partition("=")
            name = name.strip()
            if not _VAR_NAME_RE.match(name):
                continue
            variables.append((name, _clean(value)))
        return variables

    @staticmethod
    def _as_int(value: Any, default: int) -> int:
        try:
            return int(value)
        except (TypeError, ValueError):
            return default
